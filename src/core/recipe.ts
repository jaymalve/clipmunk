import { z } from "zod";
import { AudioClipSchema } from "./audio";
import { MotionSchema } from "./motion";
import { MusicSchema } from "./music";
import { fail, ok, type Result, zodIssues } from "./result";
import { SceneSchema } from "./scene";
import { SoundSchema } from "./sounds";
import { SceneVariantsSchema } from "./variants";

/** A scene recipe is the JSON half of a scene file pair. The other half is a component
 * that returns Surface elements whose ids match `definition.scene.nodes`.
 */
export const ClipIdSchema = z
  .string()
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "Use a lowercase slug: letters, digits and single hyphens.");

export const SceneDefinitionSchema = z
  .strictObject({
    width: z.number().finite().positive().max(7680).default(1400),
    height: z.number().finite().positive().max(7680).default(980),
    scene: SceneSchema,
    motion: MotionSchema.optional(),
    /** Frame sizes (and cameras) for ratio variants; a ratio not listed is fitted (core/variants.ts). */
    variants: SceneVariantsSchema.optional(),
  })
  .superRefine((definition, ctx) => {
    const ids = new Set(definition.scene.nodes.map((node) => node.id));
    definition.motion?.tracks.forEach((track, index) => {
      if (track.target.kind === "surface" && !ids.has(track.target.id))
        ctx.addIssue({
          code: "custom",
          path: ["motion", "tracks", index, "target", "id"],
          message: `Motion targets an unknown surface: ${track.target.id}`,
        });
    });
  });
export type SceneDefinition = z.output<typeof SceneDefinitionSchema>;
export type SceneDefinitionInput = z.input<typeof SceneDefinitionSchema>;

export const SceneRecipeSchema = z.strictObject({
  version: z.literal(1),
  id: ClipIdSchema,
  title: z.string().trim().min(1),
  description: z.string().optional(),
  definition: SceneDefinitionSchema,
  /** Narration recorded over the scene, or other sound; files live in .clipmunk/audio. */
  audio: z.array(AudioClipSchema).max(16).optional(),
  /** Background music generated by Clipmunk. */
  music: MusicSchema.optional(),
  /** Sound effects generated by Clipmunk, such as key clicks while text is typed. */
  sounds: z.array(SoundSchema).max(64).optional(),
  snapshot: z
    .strictObject({
      image: z
        .string()
        .max(256_000)
        .regex(/^data:image\/png;base64,[A-Za-z0-9+/]*={0,2}$/, "Use a snapshot generated by clipmunk."),
      timeMs: z.number().finite().nonnegative(),
    })
    .optional(),
});
export type SceneRecipe = z.output<typeof SceneRecipeSchema>;

export function validateDefinition(input: unknown): Result<SceneDefinition> {
  const parsed = SceneDefinitionSchema.safeParse(input);
  return parsed.success ? ok(parsed.data) : fail(zodIssues(parsed.error, "invalid-scene"));
}
export function validateRecipe(input: unknown): Result<SceneRecipe> {
  const parsed = SceneRecipeSchema.safeParse(input);
  return parsed.success ? ok(parsed.data) : fail(zodIssues(parsed.error, "invalid-scene"));
}
