export function wiringInstruction(adapter: Adapter, studioImport: string): string {
  if (adapter === "next-app" || adapter === "next-pages")
    return "No wiring needed: the studio is served at /clipmunk on the dev server.";
  return `Wrap your app once, inside the providers your scenes should share:\n\n  import { ClipmunkStudioHost } from "${studioImport}";\n\n  <ClipmunkStudioHost>\n    <App />\n  </ClipmunkStudioHost>`;
}
