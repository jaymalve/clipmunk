import { PACKAGE_NAME, STUDIO_PARAM, type Adapter } from "../core";

/** Source of every file `flick init` and `flick sync` generate.
 * Each adapter keeps Flick out of production: the import of the studio sits behind
 * the bundler's own compile-time development condition, so it is removed from builds.
 */
const HEADER = "// Generated by flick init. Safe to commit; edit by re-running `npx flick init`.\n";

export function viteStudio(typed: boolean): string {
  return `${HEADER}// Development only: a production build renders the app unchanged and contains no Flick code.
import { lazy, Suspense${typed ? ", type ReactNode" : ""} } from "react";

const active = typeof location !== "undefined" && new URLSearchParams(location.search).has("${STUDIO_PARAM}");
const scenes = import.meta.env.DEV ? import.meta.glob("./scenes/*.{scene.json,tsx,jsx}") : {};
const Studio =
  import.meta.env.DEV && active
    ? lazy(() => import("${PACKAGE_NAME}/studio").then((module) => ({ default: module.FlickStudio })))
    : null;

// The recorder loads in development only: Alt+Shift+R on any page of the app.
if (import.meta.env.DEV && typeof window !== "undefined") void import("${PACKAGE_NAME}/recorder").then((module) => module.bootRecorder());

/** Wrap the app with this, inside the providers scenes should share. */
export function FlickStudioHost({ children }${typed ? ": { children?: ReactNode }" : ""}) {
  if (!Studio) return <>{children}</>;
  return (
    <Suspense fallback={null}>
      <Studio scenes={scenes} />
    </Suspense>
  );
}
`;
}

export function reactStudio(typed: boolean): string {
  return `${HEADER}// Development only: the studio import sits behind NODE_ENV so production bundles drop it.
import { lazy, Suspense${typed ? ", type ReactNode" : ""} } from "react";

const active = typeof location !== "undefined" && new URLSearchParams(location.search).has("${STUDIO_PARAM}");
const Studio =
  process.env.NODE_ENV !== "production" && active
    ? lazy(() =>
        Promise.all([import("${PACKAGE_NAME}/studio"), import("./catalog")]).then(([studio, catalog]) => ({
          default: () => <studio.FlickStudio scenes={catalog.scenes} />,
        })),
      )
    : null;

// The recorder loads in development only: Alt+Shift+R on any page of the app.
if (process.env.NODE_ENV !== "production" && typeof window !== "undefined") void import("${PACKAGE_NAME}/recorder").then((module) => module.bootRecorder());

/** Wrap the app with this, inside the providers scenes should share. */
export function FlickStudioHost({ children }${typed ? ": { children?: ReactNode }" : ""}) {
  if (!Studio) return <>{children}</>;
  return (
    <Suspense fallback={null}>
      <Studio />
    </Suspense>
  );
}
`;
}

export function nextStudio(): string {
  return `"use client";
${HEADER}// Development only: the studio import sits behind NODE_ENV so production bundles drop it.
import dynamic from "next/dynamic";

const Studio =
  process.env.NODE_ENV !== "production"
    ? dynamic(
        () =>
          Promise.all([import("${PACKAGE_NAME}/studio"), import("./catalog")]).then(([studio, catalog]) =>
            function FlickStudioRoute() {
              return <studio.FlickStudio scenes={catalog.scenes} />;
            },
          ),
        { ssr: false },
      )
    : null;

// The recorder loads in development only: Alt+Shift+R on any page of the app.
if (process.env.NODE_ENV !== "production" && typeof window !== "undefined") void import("${PACKAGE_NAME}/recorder").then((module) => module.bootRecorder());

export default function FlickStudioHost() {
  return Studio ? <Studio /> : null;
}
`;
}

/** Next.js: a client component for the root layout, so the recorder is reachable on every route. */
export function nextRecorder(): string {
  return `"use client";
${HEADER}import { useEffect } from "react";

/** Add <FlickRecorder /> once to your root layout. It renders nothing and loads nothing in production. */
export function FlickRecorder() {
  useEffect(() => {
    if (process.env.NODE_ENV !== "production") void import("${PACKAGE_NAME}/recorder").then((module) => module.bootRecorder());
  }, []);
  return null;
}
`;
}

export function nextAppPage(importPath: string): string {
  return `${HEADER}import { notFound } from "next/navigation";
import FlickStudioHost from "${importPath}";

// The studio exists only on the development server.
export default function FlickPage() {
  if (process.env.NODE_ENV === "production") notFound();
  return <FlickStudioHost />;
}
`;
}

export function nextPagesPage(importPath: string): string {
  return `${HEADER}import FlickStudioHost from "${importPath}";

// The studio exists only on the development server.
export const getServerSideProps = async () => (process.env.NODE_ENV === "production" ? { notFound: true } : { props: {} });

export default function FlickPage() {
  return <FlickStudioHost />;
}
`;
}

/** Static scene catalog for bundlers without a glob import. `files` are names inside the scenes directory. */
export function catalog(files: readonly string[], typed: boolean): string {
  const entries = files
    .filter((file) => /\.(scene\.json|tsx|jsx)$/.test(file))
    .map((file) => `  "./scenes/${file}": () => import("./scenes/${file.replace(/\.(tsx|jsx)$/, "")}"),`);
  return `// Generated by flick sync. Do not edit: run \`npx flick sync\` after adding or removing a scene.
export const scenes${typed ? ": Record<string, () => Promise<unknown>>" : ""} = {
${entries.join("\n")}
};
`;
}

